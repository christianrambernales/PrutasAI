import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  lstat,
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  realpath,
  rename,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseModelContract } from './model-contract.mjs';

const SAFE = /^[A-Za-z0-9][A-Za-z0-9._-]*\.tflite$/;
const INSPECTOR_TIMEOUT_MS = 30_000;
const INSPECTOR_MAX_BUFFER = 1024 * 1024;
const INSPECTOR_SCRIPT = fileURLToPath(new URL('./inspect-tflite.py', import.meta.url));

function isRecord(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function hashBytes(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function simpleCompare(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function sortedRecord(value) {
  return Object.fromEntries(Object.entries(value).sort(([left], [right]) => simpleCompare(left, right)));
}

function sanitizeMessage(value) {
  return String(value ?? '')
    .replace(/[\u0000-\u001f\u007f]/g, ' ')
    .replace(/\s+/g, ' ')
    .replace(/(?:[A-Za-z]:\\|\\\\|\/)[^\s"']+/g, '[path]')
    .trim()
    .slice(0, 300);
}

export function generateRequireMap(filenames) {
  for (const filename of filenames) {
    const stem = filename.slice(0, -'.tflite'.length);
    const windowsDeviceName = /^(?:con|prn|aux|nul|com[1-9]|lpt[1-9])$/i;
    if (
      !SAFE.test(filename) ||
      filename.includes('..') ||
      windowsDeviceName.test(stem)
    ) {
      throw new Error(`invalid model filename: ${filename}`);
    }
  }
  const entries = filenames
    .map(filename => `  '${filename}': require('../../../assets/models/${filename}'),`)
    .join('\n');
  return (
    `// Generated by scripts/sync-models.mjs. Do not edit.\n` +
    `export const bundledModels: Record<string, number> = {\n${entries}\n};\n`
  );
}

function isInside(parent, candidate) {
  const pathFromParent = relative(parent, candidate);
  return pathFromParent === '' || (
    pathFromParent !== '..' &&
    !pathFromParent.startsWith(`..${sep}`) &&
    !isAbsolute(pathFromParent)
  );
}

async function resolveModelPath(modelsDir, modelsRealPath, model) {
  const candidate = resolve(modelsDir, model.file);
  let resolved;
  try {
    resolved = await realpath(candidate);
  } catch (error) {
    if (error?.code === 'ENOENT' || error?.code === 'ENOTDIR') {
      throw new Error(`${model.id}: declared model file "${model.file}" is missing from models/.`);
    }
    throw new Error(`${model.id}: unable to resolve declared model file "${model.file}".`);
  }
  if (!isInside(modelsRealPath, resolved)) {
    throw new Error(`${model.id}: model file "${model.file}" escapes models/ through a symlink.`);
  }
  let info;
  try {
    info = await stat(resolved);
  } catch {
    throw new Error(`${model.id}: unable to read declared model file "${model.file}".`);
  }
  if (!info.isFile()) {
    throw new Error(`${model.id}: declared model file "${model.file}" is not a regular file.`);
  }
  return resolved;
}

async function rejectUnlistedModelFiles(modelsDir, models) {
  const declared = new Set(models.map(model => model.file.toLowerCase()));
  let entries;
  try {
    entries = await readdir(modelsDir, { withFileTypes: true });
  } catch {
    throw new Error('Unable to read the models/ directory.');
  }
  for (const entry of entries) {
    if (entry.name.toLowerCase().endsWith('.tflite') && !declared.has(entry.name.toLowerCase())) {
      throw new Error(`Unlisted model file "${sanitizeMessage(entry.name)}" found in models/.`);
    }
  }
}

function normalizeApprovalRecord(approval) {
  return {
    ...approval,
    id: approval.id.trim(),
    inputs: approval.inputs.map(tensor => ({ ...tensor, name: tensor.name.trim() })),
    outputs: approval.outputs.map(tensor => ({ ...tensor, name: tensor.name.trim() })),
    signatures: approval.signatures.map(signature => ({
      key: signature.key,
      inputs: sortedRecord(signature.inputs),
      outputs: sortedRecord(signature.outputs),
    })),
    label_mapping: {
      output_name: approval.label_mapping.output_name.trim(),
      index_to_label: approval.label_mapping.index_to_label.map(label => label.trim()),
    },
  };
}

function normalizeTensorList(value, modelId, direction) {
  if (!Array.isArray(value) || value.length === 0 || value.length > 4096) {
    throw new Error(`${modelId}.${direction} inspector output must contain a bounded tensor list.`);
  }
  const names = new Set();
  return value.map((tensor, index) => {
    const field = `${modelId}.${direction}[${index}]`;
    if (!isRecord(tensor) || typeof tensor.name !== 'string' || tensor.name.length === 0 || tensor.name !== tensor.name.trim() || tensor.name.length > 4096 || /[\u0000-\u001f\u007f]/.test(tensor.name)) {
      throw new Error(`${field}.name is invalid.`);
    }
    if (names.has(tensor.name)) throw new Error(`${modelId}.${direction} contains duplicate tensor names.`);
    names.add(tensor.name);
    if (typeof tensor.dtype !== 'string' || !/^[A-Za-z][A-Za-z0-9_]*$/.test(tensor.dtype)) {
      throw new Error(`${field}.dtype is invalid.`);
    }
    const validShape = shape => Array.isArray(shape) && shape.length > 0 && shape.length <= 64 &&
      shape.every(dimension => Number.isSafeInteger(dimension) && dimension > 0);
    if (!validShape(tensor.shape)) throw new Error(`${field}.shape is invalid.`);
    const shapeSignature = tensor.shapeSignature === undefined ? tensor.shape : tensor.shapeSignature;
    if (
      !Array.isArray(shapeSignature) ||
      shapeSignature.length !== tensor.shape.length ||
      shapeSignature.length > 64 ||
      shapeSignature.some(dimension => !Number.isSafeInteger(dimension) || (dimension !== -1 && dimension <= 0))
    ) {
      throw new Error(`${field}.shapeSignature is invalid.`);
    }
    return {
      name: tensor.name,
      shape: [...tensor.shape],
      shapeSignature: [...shapeSignature],
      dtype: tensor.dtype,
    };
  });
}

function compareTensorList(model, direction, approved, inspected) {
  const approvedByName = new Map(approved.map(tensor => [tensor.name, tensor]));
  const inspectedByName = new Map(inspected.map(tensor => [tensor.name, tensor]));
  if (
    approvedByName.size !== inspectedByName.size ||
    [...approvedByName.keys()].some(name => !inspectedByName.has(name))
  ) {
    throw new Error(`${model.id}.${direction} tensor names do not match owner approval.`);
  }
  for (const [name, expected] of approvedByName) {
    const actual = inspectedByName.get(name);
    if (JSON.stringify(expected.shape) !== JSON.stringify(actual.shapeSignature)) {
      throw new Error(`${model.id}.${direction} tensor "${sanitizeMessage(name)}" shape does not match owner approval.`);
    }
    if (expected.dtype !== actual.dtype) {
      throw new Error(`${model.id}.${direction} tensor "${sanitizeMessage(name)}" dtype does not match owner approval.`);
    }
  }
}

function normalizeSignatures(value, model, approval) {
  if (!Array.isArray(value) || value.length > 4096) {
    throw new Error(`${model.id}.signatures inspector output must be a bounded array.`);
  }
  const inputNames = new Set(approval.inputs.map(tensor => tensor.name));
  const outputNames = new Set(approval.outputs.map(tensor => tensor.name));
  const keys = new Set();
  const signatures = value.map((signature, index) => {
    const field = `${model.id}.signatures[${index}]`;
    if (
      !isRecord(signature) ||
      typeof signature.key !== 'string' ||
      signature.key.length === 0 ||
      signature.key !== signature.key.trim() ||
      signature.key.length > 256 ||
      /[\u0000-\u001f\u007f]/.test(signature.key)
    ) {
      throw new Error(`${field}.key is invalid.`);
    }
    if (keys.has(signature.key)) throw new Error(`${model.id}.signatures contains duplicate keys.`);
    keys.add(signature.key);
    const normalizeBindings = (bindings, direction, tensorNames) => {
      if (!isRecord(bindings) || Object.keys(bindings).length === 0 || Object.keys(bindings).length > 4096) {
        throw new Error(`${field}.${direction} is invalid.`);
      }
      const targets = new Set();
      const normalized = {};
      for (const [alias, tensorName] of Object.entries(bindings)) {
        if (
          !alias || alias !== alias.trim() || alias.length > 256 ||
          /[\u0000-\u001f\u007f]/.test(alias) ||
          ['__proto__', 'constructor', 'prototype'].includes(alias) ||
          typeof tensorName !== 'string' || !tensorName || tensorName !== tensorName.trim() ||
          tensorName.length > 4096 || /[\u0000-\u001f\u007f]/.test(tensorName)
        ) {
          throw new Error(`${field}.${direction} contains invalid signature binding metadata.`);
        }
        if (!tensorNames.has(tensorName) || targets.has(tensorName)) {
          throw new Error(`${field}.${direction} does not match approved tensor names.`);
        }
        targets.add(tensorName);
        normalized[alias] = tensorName;
      }
      return sortedRecord(normalized);
    };
    return {
      key: signature.key,
      inputs: normalizeBindings(signature.inputs, 'inputs', inputNames),
      outputs: normalizeBindings(signature.outputs, 'outputs', outputNames),
    };
  }).sort((left, right) => simpleCompare(left.key, right.key));

  const approvedSignatures = approval.signatures
    .map(signature => ({
      key: signature.key,
      inputs: sortedRecord(signature.inputs),
      outputs: sortedRecord(signature.outputs),
    }))
    .sort((left, right) => simpleCompare(left.key, right.key));
  if (JSON.stringify(signatures) !== JSON.stringify(approvedSignatures)) {
    throw new Error(`${model.id}.signatures do not match owner approval.`);
  }
  return signatures;
}

function normalizeInspectorResult(result, model, approval) {
  if (!isRecord(result) || result.schemaVersion !== 1) {
    throw new Error(`${model.id}: LiteRT inspector returned an unsupported JSON contract.`);
  }
  let encoded;
  try {
    encoded = JSON.stringify(result);
  } catch {
    throw new Error(`${model.id}: LiteRT inspector returned invalid metadata.`);
  }
  if (encoded.length > INSPECTOR_MAX_BUFFER) {
    throw new Error(`${model.id}: LiteRT inspector metadata exceeds the size limit.`);
  }
  const inputs = normalizeTensorList(result.inputs, model.id, 'inputs');
  const outputs = normalizeTensorList(result.outputs, model.id, 'outputs');
  compareTensorList(model, 'inputs', approval.inputs, inputs);
  compareTensorList(model, 'outputs', approval.outputs, outputs);
  const signatures = normalizeSignatures(result.signatures, model, approval);
  return { inputs, outputs, signatures };
}

function inspectorError(result) {
  if (result.error?.code === 'ETIMEDOUT') return `LiteRT inspector timed out after ${INSPECTOR_TIMEOUT_MS / 1000} seconds.`;
  if (result.error?.code === 'ENOENT') return 'Python executable was not found; set PYTHON to a Python 3.12 interpreter.';
  if (result.error?.code === 'ENOBUFS') return 'LiteRT inspector output exceeded the size limit.';
  const diagnostic = String(result.stderr ?? '').split(/\r?\n/).map(line => line.trim()).find(Boolean) ?? '';
  if (/ai-edge-litert.*unavailable|dependency is unavailable/i.test(diagnostic)) {
    return 'ai-edge-litert is unavailable; install ml/requirements-model-inspection.txt with Python 3.12.';
  }
  if (/runtime is unavailable/i.test(diagnostic)) return 'LiteRT inspector runtime is unavailable.';
  if (/metadata.*(?:invalid|limit|exceed)|invalid .*metadata/i.test(diagnostic)) return 'LiteRT model metadata is invalid or exceeds inspection limits.';
  if (/model file is missing|unreadable|empty/i.test(diagnostic)) return 'LiteRT model file is unreadable or empty.';
  return 'LiteRT inspector could not load the model.';
}

function inspectWithLiteRT(modelPath) {
  const python = process.env.PYTHON || 'python';
  const result = spawnSync(python, [INSPECTOR_SCRIPT, modelPath], {
    encoding: 'utf8',
    maxBuffer: INSPECTOR_MAX_BUFFER,
    timeout: INSPECTOR_TIMEOUT_MS,
    killSignal: 'SIGKILL',
    windowsHide: true,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  if (result.error || result.status !== 0) {
    throw new Error(inspectorError(result));
  }
  try {
    return JSON.parse(result.stdout);
  } catch {
    throw new Error('LiteRT inspector returned invalid JSON.');
  }
}

async function exists(path) {
  try {
    await lstat(path);
    return true;
  } catch (error) {
    if (error?.code === 'ENOENT') return false;
    throw error;
  }
}

async function publishMatchedSet(transactionDir, stagedOutputs, afterPublishStep) {
  const operations = stagedOutputs.map((output, index) => ({
    ...output,
    backupPath: join(transactionDir, `backup-${index}`),
    backedUp: false,
    installed: false,
  }));
  try {
    for (const output of operations) {
      if (await exists(output.targetPath)) {
        await rename(output.targetPath, output.backupPath);
        output.backedUp = true;
      }
      await rename(output.stagedPath, output.targetPath);
      output.installed = true;
      if (afterPublishStep) await afterPublishStep(output.name);
    }
  } catch (cause) {
    const rollbackErrors = [];
    for (const output of [...operations].reverse()) {
      try {
        if (output.installed) await rm(output.targetPath, { recursive: true, force: true });
        if (output.backedUp) await rename(output.backupPath, output.targetPath);
      } catch (error) {
        rollbackErrors.push(`${output.name}: ${sanitizeMessage(error?.message)}`);
      }
    }
    if (rollbackErrors.length > 0) {
      throw new Error(`Model bundle publication failed (${sanitizeMessage(cause?.message)}); rollback failed for ${rollbackErrors.join('; ')}.`, { cause });
    }
    throw new Error(`Model bundle publication failed: ${sanitizeMessage(cause?.message)}.`, { cause });
  }
}

async function runSync(options) {
  const modelsDir = resolve(options.modelsDir);
  const appDir = resolve(options.appDir);
  let manifestText;
  let approvalsText;
  try {
    [manifestText, approvalsText] = await Promise.all([
      readFile(join(modelsDir, 'manifest.json'), 'utf8'),
      readFile(join(modelsDir, 'approval.json'), 'utf8'),
    ]);
  } catch {
    throw new Error('Model manifest or approval registry is missing or unreadable.');
  }
  const manifest = parseModelContract(manifestText, approvalsText);
  const approvalRegistry = JSON.parse(approvalsText);
  const approvalsById = new Map(approvalRegistry.approvals.map(raw => {
    const approval = normalizeApprovalRecord(raw);
    return [approval.id, approval];
  }));
  await rejectUnlistedModelFiles(modelsDir, manifest.models);
  let modelsRealPath;
  try {
    modelsRealPath = await realpath(modelsDir);
  } catch {
    throw new Error('Unable to resolve the models/ directory.');
  }

  const transactionDir = await mkdtemp(join(dirname(modelsDir), '.models-sync-'));
  const stagedAssetDir = join(transactionDir, 'assets');
  try {
    await mkdir(stagedAssetDir, { recursive: true });
    const verifiedModels = [];
    for (const model of manifest.models) {
      const approval = approvalsById.get(model.id);
      if (!approval) throw new Error(`${model.id}: owner approval is missing.`);
      const sourcePath = await resolveModelPath(modelsDir, modelsRealPath, model);
      let bytes;
      try {
        bytes = await readFile(sourcePath);
      } catch {
        throw new Error(`${model.id}: unable to read declared model file "${model.file}".`);
      }
      const computedSha256 = hashBytes(bytes);
      if (computedSha256 !== model.sha256) {
        throw new Error(`${model.id}.sha256 does not match the actual model file bytes.`);
      }

      let inspectorResult;
      try {
        inspectorResult = await options.inspectModel(sourcePath, model);
      } catch (error) {
        throw new Error(`${model.id}: LiteRT inspection failed: ${sanitizeMessage(error?.message || 'inspector failed')}.`, { cause: error });
      }
      const inspected = normalizeInspectorResult(inspectorResult, model, approval);
      const stagedModelPath = join(stagedAssetDir, model.file);
      try {
        await options.copyFile(sourcePath, stagedModelPath, bytes);
        const stagedBytes = await readFile(stagedModelPath);
        if (hashBytes(stagedBytes) !== computedSha256) {
          throw new Error('staged bytes differ from inspected bytes');
        }
      } catch (error) {
        throw new Error(`${model.id}: failed to copy model into staging: ${sanitizeMessage(error?.message || 'copy failed')}.`, { cause: error });
      }

      verifiedModels.push({
        id: model.id,
        stage: model.stage,
        file: model.file,
        version: model.version,
        sha256: computedSha256,
        fruits: [...model.fruits],
        min_confidence: model.min_confidence,
        approval: {
          status: approval.status,
          approved_by: approval.approved_by.trim(),
          approved_at: approval.approved_at.trim(),
          registry: 'models/approval.json',
        },
        inputs: inspected.inputs,
        outputs: inspected.outputs,
        signatures: inspected.signatures,
        label_mapping: {
          output_name: approval.label_mapping.output_name.trim(),
          index_to_label: approval.label_mapping.index_to_label.map(label => label.trim()),
        },
      });
    }

    const verifiedMetadata = {
      manifest_version: manifest.manifest_version,
      validation_status: 'build_validated',
      inference_status: 'unverified',
      models: verifiedModels,
    };
    const stagedBundledMap = join(transactionDir, 'bundledModels.ts');
    const stagedManifest = join(transactionDir, 'manifest.json');
    const stagedVerifiedModels = join(transactionDir, 'verifiedModels.json');
    await Promise.all([
      writeFile(stagedBundledMap, generateRequireMap(manifest.models.map(model => model.file)), { encoding: 'utf8', flag: 'wx' }),
      writeFile(stagedManifest, `${JSON.stringify(manifest, null, 2)}\n`, { encoding: 'utf8', flag: 'wx' }),
      writeFile(stagedVerifiedModels, `${JSON.stringify(verifiedMetadata, null, 2)}\n`, { encoding: 'utf8', flag: 'wx' }),
    ]);

    const mlDir = join(appDir, 'src', 'core', 'ml');
    const assetDir = join(appDir, 'assets', 'models');
    await Promise.all([mkdir(dirname(assetDir), { recursive: true }), mkdir(mlDir, { recursive: true })]);
    await publishMatchedSet(transactionDir, [
      { name: 'assets', stagedPath: stagedAssetDir, targetPath: assetDir },
      { name: 'bundledModels', stagedPath: stagedBundledMap, targetPath: join(mlDir, 'bundledModels.ts') },
      { name: 'manifest', stagedPath: stagedManifest, targetPath: join(mlDir, 'manifest.json') },
      { name: 'verifiedModels', stagedPath: stagedVerifiedModels, targetPath: join(mlDir, 'verifiedModels.json') },
    ], options.afterPublishStep);
    return { modelCount: verifiedModels.length, verifiedMetadata };
  } finally {
    await rm(transactionDir, { recursive: true, force: true }).catch(() => {});
  }
}

/**
 * Non-CLI test seam. The production command never accepts an injected inspector,
 * filesystem root, copier, or publish hook.
 */
export function syncModelsForTest({ modelsDir, appDir, inspectModel, copyFile, afterPublishStep }) {
  if (
    typeof modelsDir !== 'string' ||
    typeof appDir !== 'string' ||
    typeof inspectModel !== 'function'
  ) {
    throw new TypeError('syncModelsForTest requires explicit temporary roots and an inspector function.');
  }
  return runSync({
    modelsDir,
    appDir,
    inspectModel,
    copyFile: copyFile ?? ((_sourcePath, targetPath, bytes) => writeFile(targetPath, bytes, { flag: 'wx' })),
    afterPublishStep,
  });
}

async function main() {
  const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const result = await runSync({
    modelsDir: join(projectRoot, 'models'),
    appDir: join(projectRoot, 'app'),
    inspectModel: inspectWithLiteRT,
    copyFile: (_sourcePath, targetPath, bytes) => writeFile(targetPath, bytes, { flag: 'wx' }),
  });
  console.log(`[sync-models] bundled ${result.modelCount} model(s)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(error => {
    console.error(`[sync-models] ${sanitizeMessage(error?.message || 'model synchronization failed')}`);
    process.exitCode = 1;
  });
}
